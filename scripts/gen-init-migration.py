#!/usr/bin/env python3
"""Stop-gap generator for prisma/migrations/<ts>_init/migration.sql from prisma/schema.prisma, following Prisma's PostgreSQL output
conventions (names like Model_field_key / _idx / _fkey / _pkey). Prefer `prisma migrate dev` for every later change; CI runs
`prisma migrate diff --exit-code` to prove this output matches the schema (any drift fails the build). Usage: python3 scripts/gen-init-migration.py"""
import re, os, sys
S = open('prisma/schema.prisma').read()
enums = {m.group(1): m.group(2).split() for m in re.finditer(r'^enum (\w+) \{([^}]*)\}', S, re.M)}  # handles one-line and multi-line enums
models = [(m.group(1), m.group(2)) for m in re.finditer(r'^model (\w+) \{([\s\S]*?)^\}', S, re.M)]
names = {n for n, _ in models}
SCALAR = {'String': 'TEXT', 'Int': 'INTEGER', 'Float': 'DOUBLE PRECISION', 'Boolean': 'BOOLEAN', 'DateTime': 'TIMESTAMP(3)', 'Json': 'JSONB'}
def q(x): return f'"{x}"'
def cols(c): return ', '.join(q(x) for x in c)
def split_list(s): return [x.strip() for x in s.split(',') if x.strip()]
out = []
for en, vals in enums.items(): out.append(f'-- CreateEnum\nCREATE TYPE {q(en)} AS ENUM ({", ".join(chr(39)+v+chr(39) for v in vals)});\n')
indexes, fks = [], []
for mname, body in models:
    lines, pk = [], None; fields = []
    for raw in body.split('\n'):
        line = raw.strip()
        if not line or line.startswith('//'): continue
        if line.startswith('@@'):
            m = re.match(r'@@(id|unique|index)\(\[([^\]]*)\]', line); kind, c = m.group(1), split_list(m.group(2))
            if kind == 'id': pk = c
            elif kind == 'unique': indexes.append(f'-- CreateIndex\nCREATE UNIQUE INDEX {q(mname+"_"+"_".join(c)+"_key")} ON {q(mname)}({cols(c)});\n')
            else: indexes.append(f'-- CreateIndex\nCREATE INDEX {q(mname+"_"+"_".join(c)+"_idx")} ON {q(mname)}({cols(c)});\n')
            continue
        m = re.match(r'(\w+)\s+(\w+)(\[\])?(\?)?\s*(.*)$', line)
        if not m: continue
        name, typ, is_list, opt, attrs = m.group(1), m.group(2), bool(m.group(3)), bool(m.group(4)), m.group(5)
        if typ in names:  # relation field: may carry the FK definition
            r = re.search(r'@relation\(fields:\s*\[([^\]]*)\],\s*references:\s*\[([^\]]*)\](?:,\s*onDelete:\s*(\w+))?', attrs)
            if r:
                f, rf, od = split_list(r.group(1)), split_list(r.group(2)), r.group(3)
                fopt = all(any(re.match(rf'{c}\s+\w+\?', x.strip()) for x in body.split('\n')) for c in f)
                action = {'Cascade': 'CASCADE', 'SetNull': 'SET NULL', 'Restrict': 'RESTRICT'}.get(od, 'SET NULL' if fopt else 'RESTRICT')
                fks.append(f'-- AddForeignKey\nALTER TABLE {q(mname)} ADD CONSTRAINT {q(mname+"_"+"_".join(f)+"_fkey")} FOREIGN KEY ({cols(f)}) REFERENCES {q(typ)}({cols(rf)}) ON DELETE {action} ON UPDATE CASCADE;\n')
            continue
        if typ in SCALAR: sql = SCALAR[typ]
        elif typ in enums: sql = q(typ)
        else: sys.exit(f'unknown type {typ} in {mname}.{name}')
        nat = re.search(r'@db\.(\w+)', attrs)
        if nat: sql = {'Uuid': 'UUID', 'Timestamptz': 'TIMESTAMPTZ(3)'}.get(nat.group(1)) or sys.exit(f'unmapped native type {nat.group(1)}')
        if is_list: sql += '[]'
        d = re.search(r'@default\((.*?)\)(?:\s|$)', attrs); default = ''
        if d:
            v = d.group(1).strip()
            if v == 'now()': default = ' DEFAULT CURRENT_TIMESTAMP'
            elif v in ('uuid()', 'cuid()', 'autoincrement()'): default = ''
            elif v in ('true', 'false'): default = f' DEFAULT {v}'
            elif re.fullmatch(r'-?\d+(\.\d+)?', v): default = f' DEFAULT {v}'
            elif v.startswith('"'): default = f" DEFAULT '{v[1:-1]}'"
            elif v in enums.get(typ, []): default = f" DEFAULT '{v}'"
            else: sys.exit(f'unsupported default {v} on {mname}.{name}')
        nullable = '' if (opt or is_list) else ' NOT NULL'
        if '@id' in attrs: pk = [name]
        if '@unique' in attrs: indexes.append(f'-- CreateIndex\nCREATE UNIQUE INDEX {q(mname+"_"+name+"_key")} ON {q(mname)}({q(name)});\n')
        lines.append(f'    {q(name)} {sql}{nullable}{default},'); fields.append(name)
    lines.append(f'    CONSTRAINT {q(mname+"_pkey")} PRIMARY KEY ({cols(pk)})')
    out.append(f'-- CreateTable\nCREATE TABLE {q(mname)} (\n' + '\n'.join(lines) + '\n);\n')
sql = '\n'.join(out + indexes + fks)
d = 'prisma/migrations/20261101000000_init'; os.makedirs(d, exist_ok=True)
open(f'{d}/migration.sql', 'w').write(sql); open('prisma/migrations/migration_lock.toml', 'w').write('# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n')
# RLS script: every model table + prisma's own table
r = open('prisma/rls.sql').read().split('ALTER TABLE')[0]
r += ''.join(f'ALTER TABLE "{n}" ENABLE ROW LEVEL SECURITY;\n' for n, _ in models) + 'DO $$ BEGIN\n  IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_name = \'_prisma_migrations\') THEN\n    EXECUTE \'ALTER TABLE "_prisma_migrations" ENABLE ROW LEVEL SECURITY\';\n  END IF;\n  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = \'anon\') THEN\n    REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon, authenticated;\n  END IF;\nEND $$;\n'
open('prisma/rls.sql', 'w').write(r)
print(f'{len(models)} tables, {len(enums)} enums, {len(indexes)} indexes, {len(fks)} foreign keys -> {d}/migration.sql')
